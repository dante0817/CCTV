import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const pkg=JSON.parse(read('package.json'));
const repo=read('src/server/repositories/CameraRepository.ts');
const aiRepo=read('src/server/repositories/AiRepository.ts');
const aiService=read('src/server/services/AiDetectionService.ts');
const events=read('src/server/services/OperationalEventService.ts');
const server=read('server.ts');
must(pkg.version.startsWith('0.2.0-p0.16'),'P0.16 foundation must remain in a P0.16.x package.');
must(pkg.optionalDependencies['onnxruntime-node']==='1.30.0','optional onnxruntime-node must be pinned to 1.30.0.');
must(/CURRENT_SCHEMA_VERSION = (1[1-9]|[2-9][0-9])/.test(repo),'P0.16 migration must remain present in schema v11+.');
const match=repo.match(/migrate\(11, 'ai_person_vehicle_detection', `([\s\S]*?)`\);/); must(match,'P0.16 migration v11 missing.');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'cctv-p016-')); const db=new DatabaseSync(path.join(dir,'t.db')); db.exec('PRAGMA foreign_keys=OFF; CREATE TABLE cameras(id TEXT PRIMARY KEY); CREATE TABLE operational_events(id INTEGER PRIMARY KEY); CREATE TABLE recording_segments(id INTEGER PRIMARY KEY);'); db.exec(match[1]);
for(const table of ['camera_ai_settings','ai_detections','ai_event_recordings']){const r=db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name=?").get(table);must(r,`Missing ${table}`)} db.close();
must(aiRepo.includes("confidencePercent: 55"),'AI defaults must use 55% confidence.');
must(aiRepo.includes("enabled: false"),'AI must default off.');
must(/PERSON_CLASS\s*=\s*0/.test(aiService),'Person COCO class missing.');
must(/VEHICLE_CLASSES\s*=\s*new Set\(\[1,\s*2,\s*3,\s*5,\s*7\]\)/.test(aiService),'Vehicle COCO classes missing.');
must(aiService.includes("No face")===false,'Server implementation must not imply face recognition.');
must(events.includes("type = objectType === 'person' ? 'PERSON_DETECTED' : 'VEHICLE_DETECTED'"),'AI operational event types missing.');
must(server.includes("/api/v1/cameras/:id/ai"),'AI settings API missing.');
must(server.includes("/api/v1/events/:id/ai-context"),'AI event context API missing.');
must(server.includes("/api/v1/events/:id/ai-snapshot"),'AI snapshot API missing.');
must(read('scripts/install-ai-model.mjs').includes('f715cc2d99740d22d312777e20d9de2b2ecdc250155be8fd3752ce7e8b823521'),'AI model SHA verification missing.');
console.log('PASS P0.16 local person/vehicle AI schema, runtime, event, snapshot, and model-install foundation');
